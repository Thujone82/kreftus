import argparse
import hashlib
import json
import shutil
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _write_crlf(target: Path, text: str) -> bytes:
    normalized = text.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "\r\n")
    raw_bytes = normalized.encode("utf-8")
    for attempt in range(3):
        try:
            target.write_bytes(raw_bytes)
            break
        except OSError:
            if attempt == 2:
                raise
            time.sleep(0.2)
    return raw_bytes


def main() -> int:
    parser = argparse.ArgumentParser(description="Assemble self-contained Spire Assault Planner HTML + local-first PWA files.")
    parser.add_argument(
        "--out",
        default=str(HERE.parent / "index.html"),
        help="Output HTML path (default: ../index.html)",
    )
    args = parser.parse_args()

    shell_path = HERE / "shell.html"
    lz_path = HERE / "lz-string.js"
    if not lz_path.exists():
        lz_path = HERE.parent.parent / "trimps" / "lz-string.js"
    sim_path = HERE / "sim-engine.js"
    app_path = HERE / "app.js"
    data_path = HERE / "data.json"
    icon_192_src = HERE / "sa-icon-192.png"
    icon_512_src = HERE / "sa-icon-512.png"

    shell = shell_path.read_text(encoding="utf-8")
    lz = lz_path.read_text(encoding="utf-8")
    sim = sim_path.read_text(encoding="utf-8")
    app = app_path.read_text(encoding="utf-8")
    data = data_path.read_text(encoding="utf-8")

    data_obj = json.loads(data)
    total_builds = data_obj.get("totalBuilds") or sum(len(b) for b in data_obj.get("builds", {}).values())
    level_count = data_obj.get("levelCount") or len(data_obj.get("builds", {}))
    last_synced = data_obj.get("lastSynced") or "Unknown"
    db_meta = f"· {total_builds:,} builds across {level_count} levels · Last synced {last_synced}"

    for token in ("/*__LZ__*/", "/*__DATA__*/", "/*__SIM__*/", "/*__APP__*/"):
        if token not in shell:
            raise RuntimeError(f"Missing placeholder token {token} in shell.html")

    out_path = Path(args.out).resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    html_name = out_path.name
    manifest_name = "sa-manifest.json"
    sw_name = "sa-sw.js"

    is_dir_index = html_name.lower() == "index.html"
    pwa_start_url = "./" if is_dir_index else f"./{html_name}"
    pwa_scope = "./" if is_dir_index else f"./{html_name}"
    pwa_id = f"/{out_path.parent.name}/" if is_dir_index else f"/{out_path.parent.name}/{html_name}"

    if out_path.parent == HERE.parent:
        icon_prefix = f"{HERE.name}/"
    else:
        icon_prefix = ""
        for icon_src in (icon_192_src, icon_512_src):
            if icon_src.exists():
                shutil.copy2(icon_src, out_path.parent / icon_src.name)

    icon_192_ref = f"{icon_prefix}sa-icon-192.png"
    icon_512_ref = f"{icon_prefix}sa-icon-512.png"

    manifest_obj = {
        "id": pwa_id,
        "name": "Spire Assault Planner",
        "short_name": "Spire Assault",
        "description": "Local-first Spire Assault build advisor, live combat simulator, and upgrade ROI calculator for Trimps.",
        "start_url": pwa_start_url,
        "scope": pwa_scope,
        "display": "standalone",
        "background_color": "#08090c",
        "theme_color": "#08090c",
        "icons": [
            {
                "src": icon_192_ref,
                "sizes": "192x192",
                "type": "image/png",
                "purpose": "any",
            },
            {
                "src": icon_512_ref,
                "sizes": "512x512",
                "type": "image/png",
                "purpose": "any",
            },
        ],
    }
    manifest_text = json.dumps(manifest_obj, indent=2) + "\n"

    # Compute deterministic 12-char build hash for local-first PWA versioning & update checks
    build_hasher = hashlib.sha256()
    for p in (shell_path, lz_path, sim_path, app_path, data_path, icon_192_src, icon_512_src):
        if p.exists():
            build_hasher.update(p.read_bytes())
    build_hasher.update(manifest_text.encode("utf-8"))
    build_hash = build_hasher.hexdigest()[:12]

    html = (
        shell.replace("/*__LZ__*/", lz)
        .replace("/*__DATA__*/", data)
        .replace("/*__SIM__*/", sim)
        .replace("/*__APP__*/", app)
        .replace("/*__DB_META__*/", db_meta)
        .replace("/*__SA_BUILD_HASH__*/", build_hash)
        .replace("/*__SA_MANIFEST_HREF__*/", manifest_name)
        .replace("/*__SA_HTML_NAME__*/", html_name)
        .replace("/*__SA_SW_NAME__*/", sw_name)
        .replace("/*__SA_SW_SCOPE__*/", pwa_scope)
    )

    precache_list = [f"./{html_name}", f"./{manifest_name}", f"./{icon_192_ref}", f"./{icon_512_ref}"]
    if is_dir_index:
        precache_list.insert(0, "./")
    precache_json = json.dumps(precache_list, indent=2)

    sw_js_text = f'''/* Auto-generated by sa-build/assemble.py — Local-First Service Worker for Spire Assault Planner */
const BUILD_HASH = "{build_hash}";
const CACHE_NAME = "sa-pwa-" + BUILD_HASH;
const APP_SHELL_URL = "{pwa_start_url}";
const PRECACHE_URLS = {precache_json};

self.addEventListener("install", function (event) {{
  event.waitUntil(
    caches.open(CACHE_NAME).then(function (cache) {{
      return Promise.all(
        PRECACHE_URLS.map(function (url) {{
          return cache.add(new Request(url, {{ cache: "reload" }}));
        }})
      );
    }}).then(function () {{
      // Activate immediately on first install; wait cleanly for user confirmation on upgrades
      if (!self.registration || !self.registration.active) {{
        return self.skipWaiting();
      }}
    }})
  );
}});

self.addEventListener("activate", function (event) {{
  event.waitUntil(
    caches.keys().then(function (names) {{
      return Promise.all(
        names
          .filter(function (name) {{ return name.indexOf("sa-pwa-") === 0 && name !== CACHE_NAME; }})
          .map(function (name) {{ return caches.delete(name); }})
      );
    }}).then(function () {{
      return self.clients.claim();
    }})
  );
}});

self.addEventListener("message", function (event) {{
  var data = event.data || {{}};
  if (data.type === "SKIP_WAITING") {{
    self.skipWaiting();
  }} else if (data.type === "GET_VERSION") {{
    var payload = {{ type: "VERSION", buildHash: BUILD_HASH, cacheName: CACHE_NAME }};
    if (event.ports && event.ports[0]) {{
      event.ports[0].postMessage(payload);
    }} else if (event.source) {{
      event.source.postMessage(payload);
    }}
  }}
}});

self.addEventListener("fetch", function (event) {{
  var request = event.request;
  if (request.method !== "GET") return;
  var url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Allow explicit update checks to bypass local cache directly to network
  if (request.cache === "no-store" || url.searchParams.has("__sa_update_check")) {{
    return;
  }}

  // Local-First (Cache-First) strategy: boot instantaneously from local CacheStorage
  event.respondWith(
    caches.open(CACHE_NAME).then(function (cache) {{
      return cache.match(request, {{ ignoreSearch: true }}).then(function (cached) {{
        if (cached) return cached;
        if (request.mode === "navigate") {{
          return cache.match(APP_SHELL_URL, {{ ignoreSearch: true }}).then(function (shellCached) {{
            if (shellCached) return shellCached;
            return fetch(request).then(function (networkResp) {{
              if (networkResp && networkResp.ok) {{
                cache.put(APP_SHELL_URL, networkResp.clone());
              }}
              return networkResp;
            }});
          }});
        }}
        return fetch(request).then(function (networkResp) {{
          if (networkResp && networkResp.ok) {{
            cache.put(request, networkResp.clone());
          }}
          return networkResp;
        }});
      }});
    }})
  );
}});
'''

    raw = _write_crlf(out_path, html)
    _write_crlf(out_path.parent / manifest_name, manifest_text)
    _write_crlf(out_path.parent / sw_name, sw_js_text)

    lines = raw.count(b"\r\n") + 1
    print(
        f"Inputs   : shell={shell_path.stat().st_size:,}B | app={app_path.stat().st_size:,}B | "
        f"sim={sim_path.stat().st_size:,}B | data={data_path.stat().st_size:,}B | lz={lz_path.stat().st_size:,}B"
    )
    print(f"Assemble : Wrote {out_path.name} ({len(raw):,} bytes, {lines:,} lines, build={build_hash}, CRLF)")
    print(f"PWA      : Wrote {manifest_name} & {sw_name} (local-first Cache-First, scope {pwa_scope})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
